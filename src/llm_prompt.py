def is_policy_topic(item):
    """
    仅作为辅助分类。
    不直接决定事件是否重要。
    """

    policy_keywords = [
        "政策", "监管", "法规", "立法",
        "关税", "制裁", "补贴",
        "财政", "央行", "利率",
        "降息", "加息", "QE", "QT",
        "货币政策", "财政政策"
    ]

    text = (
        item.get("title", "") +
        " " +
        item.get("summary", "")
    ).lower()

    return any(
        keyword.lower() in text
        for keyword in policy_keywords
    )


